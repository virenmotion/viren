--   말한다. 즉 학과가 관련 없으면 학력으로는 등급을 받을 수 없다.
--
-- ⚠️ **기계가 혼자 정할 수 없다.**
--   어느 학과가 '관련 학과' 인지는 비고 6 의 산업통상자원부 고시
--   (엔지니어링기술자의 관련 자격·학력 및 경력의 인정범위 등에 관한 세부기준)에 적혀 있다.
--   그 목록을 모르는 채로 코드가 판정하면 **틀린 등급이 입찰 서류로 나간다.**
--   그래서 화면은 학과 이름으로 **추정만** 하고, 최종 판단은 이 칸에 사람이 적는다.
--   고시의 학과 목록을 받으면 그때 자동 판정으로 바꾼다.
-- =====================================================================

alter table public.employee_hr
  add column if not exists major_related text not null default ''
  check (major_related in ('', '관련 학과', '관련 없음'));

-- 결과 확인
select user_id, major, major_related from public.employee_hr;
