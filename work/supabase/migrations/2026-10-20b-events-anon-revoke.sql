-- VIREN WORK — events 테이블에서 anon(로그인 안 한 사람) 권한 회수.  2026-10-20
--
-- 왜 따로 필요한가
--   schema.sql 끝의 `revoke all on all tables ... from anon` 은 **그때 있던 테이블만**
--   처리한다. 나중에 새로 만든 테이블에는 적용되지 않아서, events 만 anon 에게
--   테이블 권한이 열린 채로 남아 있었다.
--   RLS 가 막아 주고 있어서 실제로 샌 데이터는 없다(조회하면 빈 목록이 온다).
--   다만 다른 테이블은 전부 '권한 없음'으로 끊기는데 events 만 통과하는 건
--   방어선이 한 겹 모자란 것이라 맞춘다.
--
-- ➡️ **새 테이블을 만들 때마다 이 줄을 같이 넣을 것.**
-- =====================================================================

revoke all on public.events from anon;
