/* 'YYYY-MM-DD' → 공휴일 이름, 아니면 빈 문자열 */
export function holidayName(date) {
  if (!date) return ''
  return LIST[Number(date.slice(0, 4))]?.[date.slice(5)] || ''
}

/* 달력에 공휴일을 띄울 수 있는 해인지 */
export const hasHolidays = (year) => Boolean(LIST[Number(year)])

/* 적어 둔 해의 목록 — 안내 문구에 쓴다 */
export const holidayYears = Object.keys(LIST).map(Number).sort()
