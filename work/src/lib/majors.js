export const MAJORS = new Map(
  RAW.trim().split('\n').map((line) => {
    const i = line.lastIndexOf(' ')
    return [line.slice(0, i), parseInt(line.slice(i + 1), 16)]
  }),
)

/* 명칭인정범위 (고시 머리말 그대로) —
   00학, 00과, 00학과, 00공학, 00공학과, 00학부, 00공학부, 00계열, 00전공과, 00전공학과,
   00학전공과, 00공학전공과, 00전공, 00학전공, 00과전공, 00학과전공, 00공학전공, 00공학과전공.
   긴 꼬리부터 떼어 본다. */
const SUFFIXES = [
  '공학과전공', '공학전공과', '학과전공', '공학전공', '전공학과', '학전공과',
  '공학과', '공학부', '과전공', '학전공', '전공과',
  '공학', '학과', '학부', '계열', '전공', '학', '과',
]

/* 졸업증명서에 적힌 그대로 넣어도 되게 다듬는다.
   괄호 안(야간·주간 등)과 띄어쓰기를 빼고, 가운뎃점을 하나로 맞춘다. */
const clean = (s) => String(s || '')
  .replace(/\([^)]*\)/g, '')
  .replace(/[ㆍ・]/g, '·')
  .replace(/\s+/g, '')

/* 고시 목록에서 찾는다. 찾으면 { stem, fields }, 없으면 null. */
export function findMajor(name) {
  const s = clean(name)
  if (!s) return null
  const tries = [s]
  for (const suf of SUFFIXES) {
    if (s.length > suf.length && s.endsWith(suf)) tries.push(s.slice(0, -suf.length))
  }
  for (const t of tries) {
    const mask = MAJORS.get(t)
    if (mask != null) return { stem: t, fields: FIELDS.filter((_, i) => mask & (1 << i)) }
  }
  return null
}
